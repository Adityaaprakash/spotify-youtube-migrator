package com.spotifyyoutube.migrator.matching.engine.feature;

import com.spotifyyoutube.migrator.migration.application.destination.model.DestinationTrackCandidate;

import java.util.Locale;

/**
 * Provider-neutral evidence indicating whether a destination candidate originates from
 * an official artist, record label, or distributor channel.
 * <p>
 * <b>Conservative Policy:</b> As mandated by architecture rules, a channel title containing
 * the word "official" (e.g. "Official Fan Club") is recorded as {@link #channelClaimsOfficial()},
 * but is <i>never</i> treated as conclusive proof of authenticity on its own. Authentic evidence
 * requires verified provider markers such as topic channels, VEVO syndication, exact artist channel
 * equivalence, label distributor delivery descriptions, or verified audio/video markers.
 *
 * @param isTopicChannel true if channel represents an auto-generated distributor topic channel (" - Topic")
 * @param isVevoChannel true if channel represents a VEVO verified syndication channel ("VEVO")
 * @param isArtistVerifiedName true if candidate channel matches the normalized source primary artist
 * @param isAutoGeneratedRelease true if description indicates DDEX label delivery ("Provided to YouTube by...")
 * @param hasOfficialAudioMarker true if candidate title contains verified official audio marker
 * @param hasOfficialVideoMarker true if candidate title contains verified official video marker
 * @param channelClaimsOfficial true if channel name contains "official" (unverified claim)
 */
public record OfficialSignalEvidence(
        boolean isTopicChannel,
        boolean isVevoChannel,
        boolean isArtistVerifiedName,
        boolean isAutoGeneratedRelease,
        boolean hasOfficialAudioMarker,
        boolean hasOfficialVideoMarker,
        boolean channelClaimsOfficial
) {
    /**
     * Default instance indicating no official signals detected.
     */
    public static OfficialSignalEvidence none() {
        return new OfficialSignalEvidence(false, false, false, false, false, false, false);
    }

    /**
     * Extracts official provenance signals conservatively from candidate metadata.
     *
     * @param candidate destination track candidate
     * @param normalizedPrimaryArtist normalized source primary artist name (may be null or blank)
     * @param hasOfficialAudioMarker whether title tokenization detected an official audio marker
     * @param hasOfficialVideoMarker whether title tokenization detected an official video marker
     * @return structured evidence record
     */
    public static OfficialSignalEvidence from(
            DestinationTrackCandidate candidate,
            String normalizedPrimaryArtist,
            boolean hasOfficialAudioMarker,
            boolean hasOfficialVideoMarker
    ) {
        if (candidate == null) {
            return none();
        }

        String channel = candidate.channelOrArtist() != null ? candidate.channelOrArtist().trim() : "";
        String channelLower = channel.toLowerCase(Locale.ROOT);
        String description = candidate.description() != null ? candidate.description() : "";

        boolean isTopic = channelLower.endsWith(" - topic") || channelLower.endsWith("- topic");
        boolean isVevo = channelLower.endsWith("vevo");

        boolean isArtistMatch = false;
        if (normalizedPrimaryArtist != null && !normalizedPrimaryArtist.isBlank() && !channel.isBlank()) {
            String normPrimary = normalizedPrimaryArtist.trim().toLowerCase(Locale.ROOT);
            // Match if channel is exactly the primary artist, or primary artist without topic/vevo
            if (channelLower.equals(normPrimary)
                    || (isTopic && channelLower.substring(0, channelLower.lastIndexOf("topic")).replaceAll("[- ]+$", "").equals(normPrimary))
                    || (isVevo && channelLower.substring(0, channelLower.length() - 4).trim().equals(normPrimary))) {
                isArtistMatch = true;
            }
        }

        boolean isAutoGenerated = description.contains("Provided to YouTube by")
                || description.contains("Auto-generated by YouTube");

        boolean claimsOfficial = !isTopic && !isVevo && channelLower.contains("official");

        return new OfficialSignalEvidence(
                isTopic,
                isVevo,
                isArtistMatch,
                isAutoGenerated,
                hasOfficialAudioMarker,
                hasOfficialVideoMarker,
                claimsOfficial
        );
    }

    /**
     * Determines whether credible, conservative official provenance evidence is present.
     * Note: {@link #channelClaimsOfficial()} alone is strictly excluded from confirming authenticity.
     */
    public boolean hasOfficialEvidence() {
        return isTopicChannel
                || isVevoChannel
                || isArtistVerifiedName
                || isAutoGeneratedRelease
                || hasOfficialAudioMarker
                || hasOfficialVideoMarker;
    }
}
