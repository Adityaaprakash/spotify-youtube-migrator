package com.spotifyyoutube.migrator.matching.benchmark.pool;

import com.spotifyyoutube.migrator.matching.benchmark.BenchmarkExample;
import com.spotifyyoutube.migrator.matching.benchmark.BenchmarkSourceTrack;
import com.spotifyyoutube.migrator.matching.benchmark.BenchmarkTargetCandidate;
import com.spotifyyoutube.migrator.migration.application.destination.model.DestinationTrackCandidate;

import java.time.Duration;
import java.util.List;
import java.util.Objects;

/**
 * Baseline candidate pool provider supplying solely the expected ground-truth target.
 * <p>
 * <b>Controlled Testing Only:</b> Because this provider passes only the single expected candidate
 * without distractors, ranking evaluation (Top-1 vs. Top-3) is trivial and non-discriminating.
 * This class is provided strictly for isolated component regression testing.
 */
public class TargetOnlyCandidatePoolProvider implements BenchmarkCandidatePoolProvider {

    public static final String STRATEGY_NAME = "TARGET_ONLY_NON_RANKING";

    @Override
    public List<DestinationTrackCandidate> getCandidates(BenchmarkExample example) {
        Objects.requireNonNull(example, "example must not be null");

        if (example.expectedOutcome().isMatch() && example.targetTrack() != null) {
            BenchmarkTargetCandidate target = example.targetTrack();
            BenchmarkSourceTrack source = example.sourceTrack();
            String title = target.title() != null ? target.title() : source.title();
            String channel = target.channelTitle() != null ? target.channelTitle() : source.primaryArtist();
            Duration duration = target.durationMs() != null ? Duration.ofMillis(target.durationMs()) : null;
            boolean official = target.isOfficial() != null && target.isOfficial();
            String description = official
                    ? "Provided to YouTube by Record Label\nAuto-generated by YouTube."
                    : "";

            return List.of(new DestinationTrackCandidate(
                    target.videoId(),
                    title,
                    channel,
                    description,
                    "https://i.ytimg.com/vi/" + target.videoId() + "/default.jpg",
                    "2020-01-01T00:00:00Z",
                    duration
            ));
        }

        return List.of();
    }

    @Override
    public boolean hasRealisticPool(BenchmarkExample example) {
        return false;
    }

    @Override
    public String strategyDescription() {
        return STRATEGY_NAME;
    }
}
