package com.spotifyyoutube.migrator.matching.benchmark.pool;

import com.spotifyyoutube.migrator.matching.benchmark.BenchmarkExample;
import com.spotifyyoutube.migrator.matching.benchmark.BenchmarkSourceTrack;
import com.spotifyyoutube.migrator.matching.benchmark.BenchmarkTargetCandidate;
import com.spotifyyoutube.migrator.migration.application.destination.model.DestinationTrackCandidate;

import java.time.Duration;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Objects;

/**
 * Deterministic candidate pool provider generating controlled synthetic decoys.
 * <p>
 * For positive match examples, provides the verified target candidate accompanied by
 * deterministic, challenging distractors (cover versions, live performances, remixes,
 * and same-title different-artist candidates).
 * <p>
 * <b>Provenance Transparency:</b> All synthetic distractors are deterministically generated
 * and explicitly identified with synthetic identifiers (e.g. {@code decoy_live_...}).
 * This provider returns {@code hasRealisticPool = false} to document that candidate ranking
 * is evaluated against controlled fixtures rather than live YouTube search distributions.
 */
public class ControlledDecoyCandidatePoolProvider implements BenchmarkCandidatePoolProvider {

    public static final String STRATEGY_NAME = "CONTROLLED_SYNTHETIC_DECOYS";

    private final boolean includeExpectedTarget;
    private final boolean insertDecoys;

    /**
     * Constructs a default controlled decoy provider including the expected target and distractors.
     */
    public ControlledDecoyCandidatePoolProvider() {
        this(true, true);
    }

    /**
     * Constructs a provider with customizable inclusion of target and decoys.
     *
     * @param includeExpectedTarget whether to include the expected target for positive matches
     * @param insertDecoys whether to include distractor/decoy candidates
     */
    public ControlledDecoyCandidatePoolProvider(boolean includeExpectedTarget, boolean insertDecoys) {
        this.includeExpectedTarget = includeExpectedTarget;
        this.insertDecoys = insertDecoys;
    }

    @Override
    public List<DestinationTrackCandidate> getCandidates(BenchmarkExample example) {
        Objects.requireNonNull(example, "example must not be null");

        List<DestinationTrackCandidate> pool = new ArrayList<>();
        BenchmarkSourceTrack source = example.sourceTrack();

        // 1. Convert expected target if positive match and requested
        DestinationTrackCandidate targetCandidate = null;
        if (example.expectedOutcome().isMatch() && example.targetTrack() != null && includeExpectedTarget) {
            targetCandidate = toDestinationCandidate(example.targetTrack(), source);
        }

        // 2. Generate deterministic decoys if enabled
        List<DestinationTrackCandidate> decoys = new ArrayList<>();
        if (insertDecoys) {
            decoys.addAll(generateDecoys(example));
        }

        // 3. Assemble pool with deterministic placement
        if (targetCandidate != null) {
            // Place target deterministically within the pool rather than always at index 0
            int insertIndex = (example.id().hashCode() & 0x7fffffff) % (decoys.size() + 1);
            pool.addAll(decoys);
            pool.add(insertIndex, targetCandidate);
        } else {
            pool.addAll(decoys);
        }

        return Collections.unmodifiableList(pool);
    }

    @Override
    public boolean hasRealisticPool(BenchmarkExample example) {
        return false;
    }

    @Override
    public String strategyDescription() {
        return STRATEGY_NAME;
    }

    public boolean isIncludeExpectedTarget() {
        return includeExpectedTarget;
    }

    public boolean isInsertDecoys() {
        return insertDecoys;
    }

    private DestinationTrackCandidate toDestinationCandidate(
            BenchmarkTargetCandidate target,
            BenchmarkSourceTrack source
    ) {
        String title = target.title() != null ? target.title() : source.title();
        String channel = target.channelTitle() != null ? target.channelTitle() : source.primaryArtist();
        Duration duration = target.durationMs() != null ? Duration.ofMillis(target.durationMs()) : null;
        boolean official = target.isOfficial() != null && target.isOfficial();
        String description = official
                ? "Provided to YouTube by Record Label\nAuto-generated by YouTube."
                : "Uploaded to YouTube";

        return new DestinationTrackCandidate(
                target.videoId(),
                title,
                channel,
                description,
                "https://i.ytimg.com/vi/" + target.videoId() + "/default.jpg",
                "2020-01-01T00:00:00Z",
                duration
        );
    }

    private List<DestinationTrackCandidate> generateDecoys(BenchmarkExample example) {
        BenchmarkSourceTrack source = example.sourceTrack();
        String idPrefix = "decoy_" + example.id().toLowerCase() + "_";
        Long baseDurationMs = source.durationMs() != null ? source.durationMs() : 210000L;
        List<DestinationTrackCandidate> decoys = new ArrayList<>();

        // Decoy 1: Live performance variant (incurs LIVE_MISMATCH version penalty if source is studio)
        decoys.add(new DestinationTrackCandidate(
                idPrefix + "live",
                source.title() + " (Live in Concert)",
                source.primaryArtist() + " - Topic",
                "Provided to YouTube by Label\nLive performance recording.",
                "https://i.ytimg.com/vi/live/default.jpg",
                "2019-06-15T00:00:00Z",
                Duration.ofMillis(baseDurationMs + 18000L)
        ));

        // Decoy 2: Amateur or alternate artist cover (incurs COVER version penalty)
        decoys.add(new DestinationTrackCandidate(
                idPrefix + "cover",
                source.title() + " (Acoustic Cover)",
                "Independent Cover Session",
                "Tribute cover performance.",
                "https://i.ytimg.com/vi/cover/default.jpg",
                "2021-03-20T00:00:00Z",
                Duration.ofMillis(baseDurationMs - 4000L)
        ));

        // Decoy 3: Club or EDM remix variant (incurs REMIX_MISMATCH version penalty)
        decoys.add(new DestinationTrackCandidate(
                idPrefix + "remix",
                source.title() + " (Club Extended Remix)",
                "Remix Collective",
                "Dance floor remix edition.",
                "https://i.ytimg.com/vi/remix/default.jpg",
                "2022-08-10T00:00:00Z",
                Duration.ofMillis(baseDurationMs + 45000L)
        ));

        // Decoy 4: Distinct song with same title by an unrelated artist (tests artist discrimination)
        decoys.add(new DestinationTrackCandidate(
                idPrefix + "diff_artist",
                source.title(),
                "Completely Unrelated Artist",
                "Original recording by alternate artist.",
                "https://i.ytimg.com/vi/diff_artist/default.jpg",
                "2018-11-05T00:00:00Z",
                Duration.ofMillis(baseDurationMs + 95000L)
        ));

        return decoys;
    }
}
