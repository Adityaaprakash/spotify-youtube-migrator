package com.spotifyyoutube.migrator.identity.application;

import com.spotifyyoutube.migrator.common.exception.InvalidStateException;
import com.spotifyyoutube.migrator.common.exception.ResourceNotFoundException;
import com.spotifyyoutube.migrator.identity.domain.OAuthProvider;
import com.spotifyyoutube.migrator.identity.domain.OAuthState;
import com.spotifyyoutube.migrator.identity.repository.OAuthStateRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.time.OffsetDateTime;
import java.util.Base64;
import java.util.HashSet;
import java.util.Optional;
import java.util.Set;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class OAuthStateSecurityTest {

    @Mock
    private OAuthStateRepository stateRepository;

    private OAuthStateServiceImpl stateService;

    private final UUID userA = UUID.randomUUID();
    private final UUID userB = UUID.randomUUID();

    @BeforeEach
    void setUp() {
        stateService = new OAuthStateServiceImpl(stateRepository);
    }

    @Test
    void generateState_Generates256BitCryptographicallyRandomUniqueTokens() {
        when(stateRepository.save(any(OAuthState.class))).thenAnswer(invocation -> invocation.getArgument(0));

        Set<String> generatedTokens = new HashSet<>();
        for (int i = 0; i < 50; i++) {
            OAuthState state = stateService.generateState(userA, OAuthProvider.SPOTIFY);
            assertNotNull(state.getState());
            // Decode Base64 URL-safe token without padding: must be 32 bytes (256 bits)
            byte[] decoded = Base64.getUrlDecoder().decode(state.getState());
            assertEquals(32, decoded.length, "Token must have exactly 32 bytes (256 bits) of entropy");
            assertTrue(generatedTokens.add(state.getState()), "Each generated state token must be unique");
            assertEquals(userA, state.getUserId());
            assertEquals(OAuthProvider.SPOTIFY, state.getProvider());
            assertNotNull(state.getCreatedAt());
            assertNotNull(state.getExpiresAt());
            assertTrue(state.getExpiresAt().isAfter(state.getCreatedAt()));
        }
    }

    @Test
    void generateState_RejectsNullInputs() {
        assertThrows(IllegalArgumentException.class, () -> stateService.generateState(null, OAuthProvider.SPOTIFY));
        assertThrows(IllegalArgumentException.class, () -> stateService.generateState(userA, null));
    }

    @Test
    void validateAndConsumeState_ValidState_ConsumesSuccessfully() {
        String token = "valid-token-123";
        OAuthState state = new OAuthState();
        state.setState(token);
        state.setUserId(userA);
        state.setProvider(OAuthProvider.SPOTIFY);
        state.setCreatedAt(OffsetDateTime.now());
        state.setExpiresAt(OffsetDateTime.now().plusMinutes(10));

        when(stateRepository.findByState(token)).thenReturn(Optional.of(state));
        when(stateRepository.consumeState(token)).thenReturn(1);

        OAuthState result = stateService.validateAndConsumeState(token, userA, OAuthProvider.SPOTIFY);
        assertNotNull(result);
        assertEquals(token, result.getState());
        verify(stateRepository).consumeState(token);
    }

    @Test
    void validateAndConsumeState_RejectsMismatchedUser_AntiAccountLinkingAttack() {
        String token = "state-user-a";
        OAuthState state = new OAuthState();
        state.setState(token);
        state.setUserId(userA); // Generated by User A
        state.setProvider(OAuthProvider.SPOTIFY);
        state.setExpiresAt(OffsetDateTime.now().plusMinutes(10));

        when(stateRepository.findByState(token)).thenReturn(Optional.of(state));

        // User B attempts to consume User A's OAuth state
        InvalidStateException ex = assertThrows(InvalidStateException.class, () ->
                stateService.validateAndConsumeState(token, userB, OAuthProvider.SPOTIFY));

        assertTrue(ex.getMessage().contains("does not match the authenticated user"));
        verify(stateRepository, never()).consumeState(any());
    }

    @Test
    void validateAndConsumeState_RejectsMismatchedProvider() {
        String token = "spotify-state";
        OAuthState state = new OAuthState();
        state.setState(token);
        state.setUserId(userA);
        state.setProvider(OAuthProvider.SPOTIFY);
        state.setExpiresAt(OffsetDateTime.now().plusMinutes(10));

        when(stateRepository.findByState(token)).thenReturn(Optional.of(state));

        InvalidStateException ex = assertThrows(InvalidStateException.class, () ->
                stateService.validateAndConsumeState(token, userA, OAuthProvider.GOOGLE));

        assertTrue(ex.getMessage().contains("provider mismatch"));
        verify(stateRepository, never()).consumeState(any());
    }

    @Test
    void validateAndConsumeState_RejectsBlankOrNullInputs() {
        assertThrows(InvalidStateException.class, () ->
                stateService.validateAndConsumeState(null, userA, OAuthProvider.SPOTIFY));
        assertThrows(InvalidStateException.class, () ->
                stateService.validateAndConsumeState("  ", userA, OAuthProvider.SPOTIFY));
        assertThrows(InvalidStateException.class, () ->
                stateService.validateAndConsumeState("token", null, OAuthProvider.SPOTIFY));
        assertThrows(InvalidStateException.class, () ->
                stateService.validateAndConsumeState("token", userA, null));
    }

    @Test
    void validateAndConsumeState_RejectsNonExistentState() {
        when(stateRepository.findByState("missing-token")).thenReturn(Optional.empty());

        assertThrows(ResourceNotFoundException.class, () ->
                stateService.validateAndConsumeState("missing-token", userA, OAuthProvider.SPOTIFY));
    }

    @Test
    void validateAndConsumeState_RejectsExpiredState() {
        String token = "expired-token";
        OAuthState state = new OAuthState();
        state.setState(token);
        state.setUserId(userA);
        state.setProvider(OAuthProvider.SPOTIFY);
        state.setExpiresAt(OffsetDateTime.now().minusMinutes(1)); // Expired

        when(stateRepository.findByState(token)).thenReturn(Optional.of(state));

        InvalidStateException ex = assertThrows(InvalidStateException.class, () ->
                stateService.validateAndConsumeState(token, userA, OAuthProvider.SPOTIFY));

        assertTrue(ex.getMessage().contains("expired"));
        // Verifies cleanup of expired state
        verify(stateRepository).consumeState(token);
    }

    @Test
    void validateAndConsumeState_RejectsReplayAttack_SingleUseEnforced() {
        String token = "single-use-token";
        OAuthState state = new OAuthState();
        state.setState(token);
        state.setUserId(userA);
        state.setProvider(OAuthProvider.SPOTIFY);
        state.setExpiresAt(OffsetDateTime.now().plusMinutes(10));

        when(stateRepository.findByState(token)).thenReturn(Optional.of(state));
        // Atomic consume returns 0 rows affected when another thread already consumed it
        when(stateRepository.consumeState(token)).thenReturn(0);

        InvalidStateException ex = assertThrows(InvalidStateException.class, () ->
                stateService.validateAndConsumeState(token, userA, OAuthProvider.SPOTIFY));

        assertTrue(ex.getMessage().contains("already been consumed"));
    }

    @Test
    void invalidateState_ConsumesState() {
        stateService.invalidateState("cancel-state");
        verify(stateRepository).consumeState("cancel-state");
    }

    @Test
    void purgeExpiredStates_CallsRepository() {
        when(stateRepository.deleteExpiredStates(any(OffsetDateTime.now().getClass()))).thenReturn(5);

        int purged = stateService.purgeExpiredStates();
        assertEquals(5, purged);
        verify(stateRepository).deleteExpiredStates(any());
    }
}
