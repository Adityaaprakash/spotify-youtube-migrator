package com.spotifyyoutube.migrator.matching.engine.scorer;

import com.spotifyyoutube.migrator.matching.engine.feature.CandidateTrackFeatures;
import com.spotifyyoutube.migrator.matching.engine.feature.CandidateVersionEvidence;
import com.spotifyyoutube.migrator.matching.engine.feature.OfficialSignalEvidence;
import com.spotifyyoutube.migrator.matching.engine.feature.SourceTrackFeatures;
import com.spotifyyoutube.migrator.matching.normalization.NormalizedArtistCredit;
import com.spotifyyoutube.migrator.matching.normalization.NormalizedTrackMetadata;
import com.spotifyyoutube.migrator.matching.normalization.RawTrackMetadata;
import com.spotifyyoutube.migrator.matching.normalization.TokenizedTitle;
import com.spotifyyoutube.migrator.migration.application.destination.model.DestinationTrackCandidate;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Nested;
import org.junit.jupiter.api.Test;

import java.time.Duration;
import java.util.List;
import java.util.Set;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

@DisplayName("OfficialSignalScorer Unit Tests")
class OfficialSignalScorerTest {

    private OfficialSignalScorer scorer;
    private SourceTrackFeatures source;

    @BeforeEach
    void setUp() {
        scorer = new DefaultOfficialSignalScorer();
        source = createSource("Get Lucky", "Daft Punk");
    }

    @Nested
    @DisplayName("Verified Official Provenance Signals")
    class VerifiedSignals {

        @Test
        @DisplayName("should award 1.0 for auto-generated Topic channel")
        void shouldAwardForTopicChannel() {
            OfficialSignalEvidence evidence = new OfficialSignalEvidence(
                    true, false, false, false, false, false, false
            );
            CandidateTrackFeatures candidate = createCandidateWithOfficialSignal(evidence);

            Double score = scorer.score(source, candidate);

            assertThat(score).isEqualTo(1.0);
        }

        @Test
        @DisplayName("should award 1.0 for VEVO channel")
        void shouldAwardForVevoChannel() {
            OfficialSignalEvidence evidence = new OfficialSignalEvidence(
                    false, true, false, false, false, false, false
            );
            CandidateTrackFeatures candidate = createCandidateWithOfficialSignal(evidence);

            Double score = scorer.score(source, candidate);

            assertThat(score).isEqualTo(1.0);
        }

        @Test
        @DisplayName("should award 1.0 for verified artist channel match")
        void shouldAwardForVerifiedArtistChannel() {
            OfficialSignalEvidence evidence = new OfficialSignalEvidence(
                    false, false, true, false, false, false, false
            );
            CandidateTrackFeatures candidate = createCandidateWithOfficialSignal(evidence);

            Double score = scorer.score(source, candidate);

            assertThat(score).isEqualTo(1.0);
        }

        @Test
        @DisplayName("should award 1.0 for auto-generated DDEX release description")
        void shouldAwardForAutoGeneratedRelease() {
            OfficialSignalEvidence evidence = new OfficialSignalEvidence(
                    false, false, false, true, false, false, false
            );
            CandidateTrackFeatures candidate = createCandidateWithOfficialSignal(evidence);

            Double score = scorer.score(source, candidate);

            assertThat(score).isEqualTo(1.0);
        }

        @Test
        @DisplayName("should award 1.0 for official audio title marker")
        void shouldAwardForOfficialAudioMarker() {
            OfficialSignalEvidence evidence = new OfficialSignalEvidence(
                    false, false, false, false, true, false, false
            );
            CandidateTrackFeatures candidate = createCandidateWithOfficialSignal(evidence);

            Double score = scorer.score(source, candidate);

            assertThat(score).isEqualTo(1.0);
        }

        @Test
        @DisplayName("should award 1.0 for official music video title marker")
        void shouldAwardForOfficialVideoMarker() {
            OfficialSignalEvidence evidence = new OfficialSignalEvidence(
                    false, false, false, false, false, true, false
            );
            CandidateTrackFeatures candidate = createCandidateWithOfficialSignal(evidence);

            Double score = scorer.score(source, candidate);

            assertThat(score).isEqualTo(1.0);
        }
    }

    @Nested
    @DisplayName("Conservative Protection Against Unverified Claims")
    class UnverifiedClaims {

        @Test
        @DisplayName("should award 0.0 when channel merely claims 'official' without verified proof")
        void shouldAwardZeroForUnverifiedOfficialClaim() {
            OfficialSignalEvidence evidence = new OfficialSignalEvidence(
                    false, false, false, false, false, false, true
            );
            CandidateTrackFeatures candidate = createCandidateWithOfficialSignal(evidence);

            Double score = scorer.score(source, candidate);

            assertThat(score).isEqualTo(0.0);
        }

        @Test
        @DisplayName("should award 0.0 when no official signals exist")
        void shouldAwardZeroWhenNoSignals() {
            CandidateTrackFeatures candidate = createCandidateWithOfficialSignal(OfficialSignalEvidence.none());

            Double score = scorer.score(source, candidate);

            assertThat(score).isEqualTo(0.0);
        }
    }

    @Nested
    @DisplayName("Missing Data and Validation")
    class MissingDataAndValidation {

        @Test
        @DisplayName("should return null when officialSignal evidence is absent in candidate features")
        void shouldReturnNullWhenEvidenceAbsent() {
            CandidateTrackFeatures candidate = createCandidateWithOfficialSignal(null);

            Double score = scorer.score(source, candidate);

            assertThat(score).isNull();
        }

        @Test
        @DisplayName("should throw NullPointerException when source or candidate is null")
        void shouldThrowOnNullInputs() {
            CandidateTrackFeatures candidate = createCandidateWithOfficialSignal(OfficialSignalEvidence.none());

            assertThatThrownBy(() -> scorer.score(null, candidate))
                    .isInstanceOf(NullPointerException.class);
            assertThatThrownBy(() -> scorer.score(source, null))
                    .isInstanceOf(NullPointerException.class);
        }
    }

    private SourceTrackFeatures createSource(String title, String primaryArtist) {
        NormalizedTrackMetadata metadata = new NormalizedTrackMetadata(
                RawTrackMetadata.of(title, primaryArtist, "Discovery", 248000L),
                title.toLowerCase(),
                new NormalizedArtistCredit(primaryArtist.toLowerCase(), List.of()),
                List.of(primaryArtist.toLowerCase()),
                List.of(),
                "discovery",
                Duration.ofMillis(248000),
                new TokenizedTitle(title, title, false, Set.of(), null, null, Set.of(), List.of(), List.of(), List.of())
        );
        return new SourceTrackFeatures(
                "spotify:track:1",
                title.toLowerCase(),
                title,
                primaryArtist.toLowerCase(),
                List.of(primaryArtist.toLowerCase()),
                List.of(),
                "discovery",
                Duration.ofMillis(248000),
                248000L,
                true,
                true,
                true,
                Set.of(),
                true,
                false,
                false,
                false,
                metadata
        );
    }

    private CandidateTrackFeatures createCandidateWithOfficialSignal(OfficialSignalEvidence officialSignal) {
        DestinationTrackCandidate candidate = new DestinationTrackCandidate(
                "cand-1",
                "Daft Punk - Get Lucky",
                "Daft Punk",
                "Description",
                "https://thumb.jpg",
                "2021-01-01",
                Duration.ofMillis(248000)
        );
        return new CandidateTrackFeatures(
                "cand-1",
                "Daft Punk - Get Lucky",
                "daft punk - get lucky",
                "Get Lucky",
                "Daft Punk",
                "daft punk",
                Duration.ofMillis(248000),
                248000L,
                true,
                true,
                "Description",
                "2021-01-01",
                CandidateVersionEvidence.empty(),
                officialSignal,
                candidate
        );
    }
}
