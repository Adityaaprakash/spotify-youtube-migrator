package com.spotifyyoutube.migrator.matching.engine.feature;

import com.spotifyyoutube.migrator.migration.application.destination.model.DestinationTrackCandidate;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Nested;
import org.junit.jupiter.api.Test;

import java.time.Duration;

import static org.assertj.core.api.Assertions.assertThat;

@DisplayName("OfficialSignalEvidence Tests")
class OfficialSignalEvidenceTest {

    private DestinationTrackCandidate candidate(String channel, String description) {
        return new DestinationTrackCandidate(
                "vid-123",
                "Song Title",
                channel,
                description,
                "https://thumb.jpg",
                "2021-01-01",
                Duration.ofSeconds(200)
        );
    }

    @Nested
    @DisplayName("Topic and VEVO Channels")
    class TopicAndVevoChannels {

        @Test
        @DisplayName("should detect auto-generated Topic channel")
        void shouldDetectTopicChannel() {
            DestinationTrackCandidate c = candidate("Daft Punk - Topic", null);
            OfficialSignalEvidence evidence = OfficialSignalEvidence.from(c, "Daft Punk", false, false);

            assertThat(evidence.isTopicChannel()).isTrue();
            assertThat(evidence.isVevoChannel()).isFalse();
            assertThat(evidence.isArtistVerifiedName()).isTrue();
            assertThat(evidence.hasOfficialEvidence()).isTrue();
        }

        @Test
        @DisplayName("should detect VEVO syndication channel")
        void shouldDetectVevoChannel() {
            DestinationTrackCandidate c = candidate("DuaLipaVEVO", null);
            OfficialSignalEvidence evidence = OfficialSignalEvidence.from(c, "Dua Lipa", false, false);

            assertThat(evidence.isTopicChannel()).isFalse();
            assertThat(evidence.isVevoChannel()).isTrue();
            assertThat(evidence.isArtistVerifiedName()).isTrue();
            assertThat(evidence.hasOfficialEvidence()).isTrue();
        }
    }

    @Nested
    @DisplayName("Artist Channel Equivalence")
    class ArtistChannelEquivalence {

        @Test
        @DisplayName("should detect exact case-insensitive artist match")
        void shouldDetectExactArtistMatch() {
            DestinationTrackCandidate c = candidate("Coldplay", null);
            OfficialSignalEvidence evidence = OfficialSignalEvidence.from(c, "coldplay", false, false);

            assertThat(evidence.isArtistVerifiedName()).isTrue();
            assertThat(evidence.hasOfficialEvidence()).isTrue();
        }

        @Test
        @DisplayName("should not mark artist match when names diverge")
        void shouldNotMarkArtistMatchWhenNamesDiverge() {
            DestinationTrackCandidate c = candidate("Some Fan Channel", null);
            OfficialSignalEvidence evidence = OfficialSignalEvidence.from(c, "Coldplay", false, false);

            assertThat(evidence.isArtistVerifiedName()).isFalse();
            assertThat(evidence.hasOfficialEvidence()).isFalse();
        }
    }

    @Nested
    @DisplayName("Label Distributor Delivery Descriptions")
    class LabelDistributorDeliveryDescriptions {

        @Test
        @DisplayName("should detect 'Provided to YouTube by' description marker")
        void shouldDetectProvidedToYouTube() {
            DestinationTrackCandidate c = candidate(
                    "Warner Music",
                    "Provided to YouTube by Warner Music Group\n\nSong Title · Dua Lipa"
            );
            OfficialSignalEvidence evidence = OfficialSignalEvidence.from(c, "Dua Lipa", false, false);

            assertThat(evidence.isAutoGeneratedRelease()).isTrue();
            assertThat(evidence.hasOfficialEvidence()).isTrue();
        }

        @Test
        @DisplayName("should detect 'Auto-generated by YouTube' description marker")
        void shouldDetectAutoGeneratedByYouTube() {
            DestinationTrackCandidate c = candidate(
                    "Unknown Channel",
                    "Auto-generated by YouTube.\n\nSong Title"
            );
            OfficialSignalEvidence evidence = OfficialSignalEvidence.from(c, "Daft Punk", false, false);

            assertThat(evidence.isAutoGeneratedRelease()).isTrue();
            assertThat(evidence.hasOfficialEvidence()).isTrue();
        }
    }

    @Nested
    @DisplayName("Conservative Policy for Channel Claiming Official")
    class ConservativePolicyForChannelClaimingOfficial {

        @Test
        @DisplayName("channel name containing 'official' is recorded as claim but DOES NOT prove authenticity")
        void channelContainingOfficialDoesNotProveAuthenticity() {
            DestinationTrackCandidate c = candidate("Queen Official Fans", "Fan uploads");
            OfficialSignalEvidence evidence = OfficialSignalEvidence.from(c, "Different Artist", false, false);

            assertThat(evidence.channelClaimsOfficial()).isTrue();
            // Critical rule: channelClaimsOfficial alone MUST NOT set hasOfficialEvidence to true!
            assertThat(evidence.hasOfficialEvidence()).isFalse();
        }

        @Test
        @DisplayName("official video/audio marker confirms official signal")
        void officialVideoMarkerConfirmsOfficialSignal() {
            DestinationTrackCandidate c = candidate("Random Uploader", "No description");
            OfficialSignalEvidence evidence = OfficialSignalEvidence.from(c, "Different Artist", true, false);

            assertThat(evidence.hasOfficialAudioMarker()).isTrue();
            assertThat(evidence.hasOfficialEvidence()).isTrue();
        }
    }

    @Nested
    @DisplayName("Null and Empty Safety")
    class NullAndEmptySafety {

        @Test
        @DisplayName("none factory produces all false flags")
        void noneProducesAllFalseFlags() {
            OfficialSignalEvidence evidence = OfficialSignalEvidence.none();

            assertThat(evidence.isTopicChannel()).isFalse();
            assertThat(evidence.isVevoChannel()).isFalse();
            assertThat(evidence.isArtistVerifiedName()).isFalse();
            assertThat(evidence.isAutoGeneratedRelease()).isFalse();
            assertThat(evidence.hasOfficialAudioMarker()).isFalse();
            assertThat(evidence.hasOfficialVideoMarker()).isFalse();
            assertThat(evidence.channelClaimsOfficial()).isFalse();
            assertThat(evidence.hasOfficialEvidence()).isFalse();
        }

        @Test
        @DisplayName("null candidate safely returns none evidence")
        void nullCandidateSafelyReturnsNone() {
            OfficialSignalEvidence evidence = OfficialSignalEvidence.from(null, "Artist", false, false);
            assertThat(evidence).isEqualTo(OfficialSignalEvidence.none());
        }
    }
}
